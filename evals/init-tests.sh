#!/usr/bin/env bash
# Deterministic eval for opt #3 — no Claude, free. Two layers:
#  (1) the bin/claudehut-init SCRIPT writes the canonical plane + stack-gated rules + idempotent @import;
#  (2) the SessionStart FALLBACK (bootstrap.sh auto-running the script when the plane is absent) — which IS
#      the live INVOCATION path, but model-independent, so it is verifiable here (the model is not in that loop).
# P7 separately measured the skill's !`…` invocation as flaky (2/3); the bootstrap fallback is the reliable close.
# Run: evals/init-tests.sh   (see evals/FOLLOWUP-init-script.md §12)
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
INIT="$ROOT/bin/claudehut-init"
PASS=0; FAIL=0
ok(){ PASS=$((PASS+1)); echo "  ok   - $1"; }
bad(){ FAIL=$((FAIL+1)); echo "  FAIL - $1"; }
command -v jq >/dev/null 2>&1 || { echo "jq required"; exit 2; }

run_init() { local src="$1" w; w="$(mktemp -d)/work"; mkdir -p "$w"; cp -R "$src/." "$w/" 2>/dev/null; CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$w" >/dev/null 2>&1; echo "$w"; }
prov(){ head -1 "$1" 2>/dev/null | grep -q 'generated by claudehut-init\|ClaudeHut rule template'; }

echo "== plane generation + idempotency (clean-first-run) =="
W="$(run_init "$ROOT/evals/tasks/clean-first-run/repo")"
for f in MEMORY.md PROJECT.md LANGUAGE.md architecture.md reuse-index.json; do
  [ -f "$W/.claude/claudehut/$f" ] && ok "plane: $f written" || bad "plane: $f MISSING"
done
prov "$W/.claude/claudehut/MEMORY.md" && ok "provenance line present" || bad "no provenance line"
# MEM-2 — the budget must be stated in BYTES. Measured across the 15 real installs: only party-ms (468 lines)
# violates the old "≤ ~150 lines" rule, while auth-ms (94 L / 35,797 B), payment-orchestrator-ms (65 L /
# 11,501 B) and java-common-ms (37 L / 9,328 B) all PASS it at 9-36 KB. Three of the four over-budget files
# are invisible to a line count, so the unit itself was the defect. 8192 is the one literal; row 1's
# migration test asserts the same number.
grep -q '8192 bytes' "$W/.claude/claudehut/MEMORY.md" \
  && ok "MEM-2: MEMORY.md states a BYTE budget (8192)" \
  || bad "MEM-2: MEMORY.md carries no byte budget"
grep -qE 'Keep it concise \(. ~150 lines\)' "$W/.claude/claudehut/MEMORY.md" \
  && bad "MEM-2: the line budget survived — 3 of 4 real over-budget files pass it" \
  || ok "MEM-2: the misleading line budget is gone"
jq -e . "$W/.claude/claudehut/reuse-index.json" >/dev/null 2>&1 && ok "reuse-index.json valid JSON" || bad "reuse-index.json invalid"
grep -q '{{' "$W/.claude/claudehut/PROJECT.md" && bad "unsubstituted {{...}} in PROJECT.md" || ok "no unsubstituted tokens in PROJECT.md"
grep -q 'com\.example' "$W/.claude/claudehut/PROJECT.md" && ok "base package detected (com.example, single-file repo)" || bad "base package wrong"
[ -f "$W/.claude/claudehut/learnings.jsonl" ] && ok "learnings.jsonl created" || bad "learnings.jsonl missing"
echo seed > "$W/.claude/claudehut/learnings.jsonl"   # idempotency: must NOT be clobbered on re-run
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$W" >/dev/null 2>&1   # second run
n=$(grep -c 'project-adaptive memory' "$W/CLAUDE.md" 2>/dev/null || echo 0)
[ "$n" = "1" ] && ok "@import idempotent (1 block after 2 runs)" || bad "@import not idempotent ($n blocks)"
[ "$(cat "$W/.claude/claudehut/learnings.jsonl")" = "seed" ] && ok "learnings.jsonl not clobbered on re-run" || bad "learnings.jsonl clobbered"
rm -rf "$W"

echo "== stack-gating (reactive-kafka: webflux + r2dbc + kafka + redis) =="
W="$(run_init "$ROOT/evals/tasks/_fixtures/reactive-kafka")"; R="$W/.claude/rules"
for want in framework/webflux.md framework/r2dbc.md framework/kafka-consumer.md framework/kafka-producer.md framework/redis.md performance/backpressure.md testing/stepverifier.md; do
  [ -f "$R/$want" ] && ok "emitted: $want" || bad "missing: $want"
done
for no in framework/spring-mvc.md framework/jpa.md framework/nats.md framework/rabbitmq.md; do
  [ -f "$R/$no" ] && bad "should NOT emit: $no" || ok "gated out: $no"
done
grep -q 'com\.acme\.app' "$W/.claude/claudehut/PROJECT.md" && ok "base package (com.acme.app)" || bad "base package wrong (reactive-kafka)"
rm -rf "$W"

echo "== architecture axis (arch=): declared, never guessed =="
# ddd / hexagonal / cqrs are mutually exclusive. All three shipped untagged, so every project received three
# contradictory architecture rules at once. There is no trustworthy detector, so the default emits NONE and a
# project opts in with CLAUDEHUT_ARCH. These assertions pin both halves of that behaviour.
W="$(run_init "$ROOT/evals/tasks/_fixtures/servlet-jpa")"; R="$W/.claude/rules"
for no in architecture/ddd.md architecture/hexagonal.md architecture/cqrs.md; do
  [ -f "$R/$no" ] && bad "arch: should NOT emit by default: $no" || ok "arch: gated out by default: $no"
done
[ -f "$R/architecture/package-layout.md" ] && ok "arch: untagged architecture rules still emitted" \
  || bad "arch: the axis gated out an UNTAGGED architecture rule"
rm -rf "$W"
W="$(CLAUDEHUT_ARCH=hexagonal run_init "$ROOT/evals/tasks/_fixtures/servlet-jpa")"; R="$W/.claude/rules"
[ -f "$R/architecture/hexagonal.md" ] && ok "arch: CLAUDEHUT_ARCH=hexagonal emits hexagonal.md" \
  || bad "arch: opt-in did not emit the declared style"
{ [ ! -f "$R/architecture/ddd.md" ] && [ ! -f "$R/architecture/cqrs.md" ]; } \
  && ok "arch: opt-in emits ONLY the declared style" || bad "arch: opt-in emitted a competing style"
rm -rf "$W"
# Assert on the WARNING, not just on the absence of files: `arch=bogus` matches no template tag either way,
# so file-absence alone stays green even if the validation is deleted outright.
WT="$(mktemp -d)"; cp -R "$ROOT/evals/tasks/_fixtures/servlet-jpa/." "$WT/"
warn_out="$(CLAUDEHUT_ARCH=bogus CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WT" 2>&1)"
# The style may now come from PROJECT.md as well as the env var, so the warning names the value rather than
# claiming a source. The assertion still requires a warn line that quotes the rejected value back.
printf '%s' "$warn_out" | grep -qi "warn:.*'bogus'" \
  && ok "arch: an unrecognised CLAUDEHUT_ARCH is REJECTED with a warning (not silently passed through)" \
  || bad "arch: unrecognised CLAUDEHUT_ARCH produced no warning — validation missing"
{ [ ! -f "$WT/.claude/rules/architecture/ddd.md" ] && [ ! -f "$WT/.claude/rules/architecture/hexagonal.md" ] \
  && [ ! -f "$WT/.claude/rules/architecture/cqrs.md" ]; } \
  && ok "arch: an unrecognised CLAUDEHUT_ARCH emits no style" || bad "arch: unrecognised CLAUDEHUT_ARCH emitted a style"
rm -rf "$WT"

# Upgrade path: projects created before the arch axis hold all three styles. bootstrap.sh runs
# --refresh-rules automatically on a version bump, so a refresh that only SKIPS inactive rules would report
# success while leaving the exact contradiction the axis removes.
WU="$(mktemp -d)"; cp -R "$ROOT/evals/tasks/_fixtures/servlet-jpa/." "$WU/"
mkdir -p "$WU/.claude/rules/architecture"
for s in ddd hexagonal cqrs; do cp "$ROOT/templates/rules/architecture/$s.md" "$WU/.claude/rules/architecture/$s.md"; done
printf '\n## Learned pitfalls\n- project knowledge\n' >> "$WU/.claude/rules/architecture/cqrs.md"
# --refresh-rules runs AUTOMATICALLY from scripts/bootstrap.sh on every plugin version bump, with output
# discarded. So it must never delete: a user who upgrades has typed no command and sees no message. It
# REPORTS stale rules; removal is opt-in via --retire-inactive.
out="$(CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WU" --refresh-rules 2>&1)"
{ [ -f "$WU/.claude/rules/architecture/ddd.md" ] && [ -f "$WU/.claude/rules/architecture/hexagonal.md" ]; } \
  && ok "arch: --refresh-rules alone NEVER deletes a rule (safe automatic upgrade path)" \
  || bad "arch: automatic refresh deleted rules without consent"
printf '%s' "$out" | grep -q 'stale: architecture/ddd.md' \
  && ok "arch: --refresh-rules REPORTS stale rules instead of silently keeping them" \
  || bad "arch: stale rules are not reported"
grep -q 'project knowledge' "$WU/.claude/rules/architecture/cqrs.md" \
  && ok "arch: refresh preserves learner-promoted pitfalls" || bad "arch: refresh damaged learned pitfalls"
# ...and the explicit flag does remove them, still never touching a file holding learned pitfalls
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WU" --refresh-rules --retire-inactive >/dev/null 2>&1
{ [ ! -f "$WU/.claude/rules/architecture/ddd.md" ] && [ ! -f "$WU/.claude/rules/architecture/hexagonal.md" ]; } \
  && ok "arch: --retire-inactive removes stranded rules when asked by name" \
  || bad "arch: --retire-inactive did not remove stranded rules"
{ [ -f "$WU/.claude/rules/architecture/cqrs.md" ] && grep -q 'project knowledge' "$WU/.claude/rules/architecture/cqrs.md"; } \
  && ok "arch: --retire-inactive still never destroys learner-promoted pitfalls" \
  || bad "arch: --retire-inactive deleted a rule holding learned pitfalls"
rm -rf "$WU"

echo "== stack-gating (servlet-jpa: mvc + jpa + postgres) =="
W="$(run_init "$ROOT/evals/tasks/_fixtures/servlet-jpa")"; R="$W/.claude/rules"
for want in framework/spring-mvc.md framework/jpa.md coding/naming.md security/owasp-top10.md; do
  [ -f "$R/$want" ] && ok "emitted: $want" || bad "missing: $want"
done
for no in framework/webflux.md framework/r2dbc.md framework/redis.md testing/stepverifier.md; do
  [ -f "$R/$no" ] && bad "should NOT emit: $no" || ok "gated out: $no"
done
rm -rf "$W"

echo "== tag axes that never matched (dead rules) =="
# testing/testcontainers.md carried `test=testcontainers` with no `test=` axis to match, and
# performance/caching.md carried `cache=redis,caffeine` matched as ONE literal token against an ACTIVE
# holding `cache=redis`. Both rules shipped in the repo and reached zero projects.
WD="$(mktemp -d)"; cp -R "$ROOT/evals/tasks/_fixtures/reactive-kafka/." "$WD/"
printf '\ndependencies { testImplementation "org.testcontainers:postgresql" }\n' >> "$WD/build.gradle"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WD" >/dev/null 2>&1
[ -f "$WD/.claude/rules/testing/testcontainers.md" ] \
  && ok "tags: test=testcontainers axis exists and emits for a testcontainers project" \
  || bad "tags: testcontainers.md is dead — no test= axis"
[ -f "$WD/.claude/rules/performance/caching.md" ] \
  && ok "tags: comma-list tag matches on its FIRST listed value (cache=redis)" \
  || bad "tags: comma-list tag never matches — caching.md is dead"
rm -rf "$WD"
# The second element is the one that actually proves alternatives work: a bare `caffeine` has no axis prefix,
# so before axis-inheritance it could never match an ACTIVE token, and a redis-only fixture could not tell.
WC="$(mktemp -d)"
printf 'plugins { id "java" }\ndependencies { implementation "com.github.ben-manes.caffeine:caffeine:3.1.8" }\n' > "$WC/build.gradle"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WC" >/dev/null 2>&1
[ -f "$WC/.claude/rules/performance/caching.md" ] \
  && ok "tags: comma-list tag matches on a NON-first value too (cache=caffeine)" \
  || bad "tags: only the first listed value ever matches — alternatives are a false claim"
[ ! -f "$WC/.claude/rules/framework/redis.md" ] \
  && ok "tags: a caffeine project does not receive redis rules" || bad "tags: caffeine project got redis rules"
rm -rf "$WC"
WN="$(run_init "$ROOT/evals/tasks/_fixtures/servlet-jpa")"
{ [ ! -f "$WN/.claude/rules/testing/testcontainers.md" ] && [ ! -f "$WN/.claude/rules/performance/caching.md" ]; } \
  && ok "tags: neither emits for a project that uses neither" || bad "tags: emitted a rule for an inactive axis"
rm -rf "$WN"

echo "== --detect (servlet-jpa) =="
D="$(CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$ROOT/evals/tasks/_fixtures/servlet-jpa" --detect 2>/dev/null)"
echo "$D" | jq -e '.web=="mvc" and .orm=="jpa" and .db=="postgresql" and .base_package=="com.acme.web"' >/dev/null 2>&1 \
  && ok "--detect correct (web=mvc orm=jpa db=postgresql base=com.acme.web)" || bad "--detect wrong: $D"

echo "== fallback: bootstrap.sh (SessionStart) auto-generates the plane — opt #3 INVOCATION fix =="
# Faithfully replicates SessionStart: the hook pipes its JSON payload to bootstrap.sh. The model is NOT
# in the loop here, so this deterministically proves the fallback closes #3's invocation gap.
W="$(mktemp -d)/work"; mkdir -p "$W"; cp -R "$ROOT/evals/tasks/clean-first-run/repo/." "$W/"
echo '{"session_id":"p7fb","source":"startup"}' | CLAUDE_PROJECT_DIR="$W" CLAUDE_PLUGIN_ROOT="$ROOT" bash "$ROOT/scripts/bootstrap.sh" >/dev/null 2>&1
fp=0; for f in MEMORY.md PROJECT.md LANGUAGE.md architecture.md reuse-index.json; do [ -f "$W/.claude/claudehut/$f" ] && fp=$((fp+1)); done
[ "$fp" = 5 ] && ok "SessionStart fallback wrote the plane (5/5, zero model reliance)" || bad "fallback plane=$fp/5"
[ -f "$W/.claude/claudehut/state/p7fb.json" ] && ok "fallback also armed state (p7fb.json)" || bad "fallback did not arm state"
[ -d "$W/.claudehut" ] && bad "fallback created wrong-dir .claudehut/" || ok "fallback: no wrong-dir .claudehut/"
rm -rf "$W"

echo "== worktree.baseRef=head settings write (v0.5.0 — dependent-phase fan-out) =="
# create case: no settings.json -> init creates it with baseRef=head
W="$(run_init "$ROOT/evals/tasks/clean-first-run/repo")"
[ "$(jq -r '.worktree.baseRef // empty' "$W/.claude/settings.json" 2>/dev/null)" = "head" ] \
  && ok "init created .claude/settings.json with worktree.baseRef=head" || bad "settings.json baseRef not head"
# merge case: pre-existing settings keys must be PRESERVED, baseRef added
SRC="$(mktemp -d)/repo"; mkdir -p "$SRC/.claude"; cp -R "$ROOT/evals/tasks/clean-first-run/repo/." "$SRC/" 2>/dev/null
mkdir -p "$SRC/.claude"; printf '{"env":{"FOO":"bar"},"enabledPlugins":{"x":true}}' > "$SRC/.claude/settings.json"
W2="$(run_init "$SRC")"
b=$(jq -r '.worktree.baseRef // empty' "$W2/.claude/settings.json" 2>/dev/null)
foo=$(jq -r '.env.FOO // empty' "$W2/.claude/settings.json" 2>/dev/null)
[ "$b" = "head" ] && [ "$foo" = "bar" ] \
  && ok "init merges baseRef=head WITHOUT clobbering existing settings keys (env.FOO preserved)" \
  || bad "settings merge wrong (baseRef=$b env.FOO=$foo)"
# idempotent: second run keeps exactly one baseRef, still head
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$W2" >/dev/null 2>&1
[ "$(jq -r '.worktree.baseRef' "$W2/.claude/settings.json" 2>/dev/null)" = "head" ] \
  && ok "settings baseRef idempotent on re-run" || bad "settings baseRef changed on re-run"
rm -rf "$W" "$W2"

echo "== .worktreeinclude (v0.6.0 — native gitignored-config copy into agent worktrees) =="
W3="$(run_init "$ROOT/evals/tasks/clean-first-run/repo")"
[ -f "$W3/.worktreeinclude" ] && ok "init created .worktreeinclude at project root" || bad "init did not create .worktreeinclude"
grep -q '\.env' "$W3/.worktreeinclude" 2>/dev/null && ok ".worktreeinclude seeds gitignored config (.env)" || bad ".worktreeinclude missing seed entries"
# idempotent + never clobber: user edits survive a re-run
printf 'custom-secret.json\n' > "$W3/.worktreeinclude"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$W3" >/dev/null 2>&1
grep -q 'custom-secret.json' "$W3/.worktreeinclude" 2>/dev/null && ok ".worktreeinclude not clobbered on re-run (user edits preserved)" || bad ".worktreeinclude clobbered on re-run"
rm -rf "$W3"

echo; echo "== RULE-17: --audit reports drift read-only =="
# --refresh-rules only reports stale rules while RE-EMITTING, and bootstrap.sh runs it with stdout
# discarded on every version bump, so the report never reached a human. --audit reaches an already-stamped
# repo without needing a version change, and must write NOTHING.
WE="$(mktemp -d)/repo"; mkdir -p "$WE/src/main/java/com/x"; touch "$WE/src/main/java/com/x/A.java"
printf 'dependencies { implementation("org.springframework.boot:spring-boot-starter-data-jpa") }\n' > "$WE/build.gradle.kts"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WE" >/dev/null 2>&1
# strand a rule the way a real upgrade does: emitted once, then its axis goes inactive
mkdir -p "$WE/.claude/rules/architecture"; cp "$ROOT/templates/rules/architecture/ddd.md" "$WE/.claude/rules/architecture/ddd.md"
files_before="$(find "$WE" | wc -l | tr -d ' ')"
aud="$(CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WE" --audit 2>&1)"
files_after="$(find "$WE" | wc -l | tr -d ' ')"
[ "$files_before" = "$files_after" ] \
  && ok "RULE-17: --audit writes nothing (file count unchanged)" \
  || bad "RULE-17: --audit created or removed files ($files_before -> $files_after)"
printf '%s' "$aud" | grep -q 'stale:   architecture/ddd.md' \
  && ok "RULE-17: --audit names the stranded rule" \
  || bad "RULE-17: --audit did not report a stranded rule"
printf '%s' "$aud" | grep -qE '^  summary: [0-9]+ stale, [0-9]+ missing' \
  && ok "RULE-17: --audit ends with a machine-readable summary line" \
  || bad "RULE-17: --audit has no summary line for bootstrap to surface"
printf '%s' "$aud" | grep -q 'note: no architecture style' \
  && bad "RULE-17: --audit output is polluted by the arch note" \
  || ok "RULE-17: --audit emits only the report"
rm -rf "$WE"
# bootstrap must carry the summary into systemMessage rather than discarding it
grep -q 'claudehut-init" "$PROJECT_DIR" --audit' "$ROOT/scripts/bootstrap.sh" \
  && ok "RULE-01: bootstrap re-derives the drift summary after a version-bump refresh" \
  || bad "RULE-01: bootstrap still discards the refresh report with nothing in its place"
grep -q 'rule drift after the plugin upgrade' "$ROOT/scripts/bootstrap.sh" \
  && ok "RULE-01: drift reaches the user through systemMessage" \
  || bad "RULE-01: drift is computed but never surfaced"

echo; echo "== RULE-16: the architecture style is declarable and durable =="
# The arch axis was reachable only through CLAUDEHUT_ARCH, and no real install sets it -- so the three
# architecture rules never emit on a fresh init, while every project made before the axis existed still
# carries all three contradictory files. The choice now lives in PROJECT.md, which survives re-runs.
WC="$(mktemp -d)/repo"; mkdir -p "$WC/src/main/java/com/x"; touch "$WC/src/main/java/com/x/A.java"
printf 'dependencies { implementation("org.springframework.boot:spring-boot-starter-web") }\n' > "$WC/build.gradle.kts"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WC" >/dev/null 2>&1
grep -q '^- Architecture style: none' "$WC/.claude/claudehut/PROJECT.md" \
  && ok "RULE-16: PROJECT.md carries a declarable architecture style, defaulting to none" \
  || bad "RULE-16: PROJECT.md has no architecture-style line"
[ -f "$WC/.claude/rules/architecture/ddd.md" ] \
  && bad "RULE-16: an arch rule was emitted with no style declared" \
  || ok "RULE-16: no arch rule emitted while the style is none (styles are mutually exclusive)"
perl -pi -e 's/^- Architecture style: none/- Architecture style: ddd/' "$WC/.claude/claudehut/PROJECT.md"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WC" >/dev/null 2>&1
[ -f "$WC/.claude/rules/architecture/ddd.md" ] \
  && ok "RULE-16: a style declared in PROJECT.md is read back on the next run (no env var needed)" \
  || bad "RULE-16: the declared style was ignored — the axis is still env-var-only"
rm -rf "$WC"
# db must use the same bare `none` as every other axis; "(none)" could never match a db=none tag
WD="$(mktemp -d)/repo"; mkdir -p "$WD/src/main/java/com/x"; touch "$WD/src/main/java/com/x/A.java"
printf 'dependencies { implementation("org.springframework.boot:spring-boot-starter-web") }\n' > "$WD/build.gradle.kts"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WD" --detect | grep -q '"db":"none"' \
  && ok "RULE-16: the db axis reports bare none, consistent with every other axis" \
  || bad "RULE-16: the db axis still reports (none) — a db=none tag could never match it"
rm -rf "$WD"

echo; echo "== RULE-15: the java= axis gates version-specific rules =="
# JAVA_VERSION was detected and printed but never entered ACTIVE, so framework/virtual-threads.md (Java 21)
# and coding/records-sealed.md (17+) installed into Java 8 and 11 projects, teaching APIs that do not
# compile there. The matcher is exact-string, hence a bucketed axis rather than a numeric comparison.
jv_case() { # $1 version -> echoes "<virtual-threads> <records-sealed>"
  local w; w="$(mktemp -d)/repo"; mkdir -p "$w/src/main/java/com/x"; touch "$w/src/main/java/com/x/A.java"
  printf 'java { sourceCompatibility = %s }\ndependencies { implementation("org.springframework.boot:spring-boot-starter-web") }\n' "$1" > "$w/build.gradle.kts"
  CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$w" >/dev/null 2>&1
  printf '%s %s' \
    "$([ -f "$w/.claude/rules/framework/virtual-threads.md" ] && echo yes || echo no)" \
    "$([ -f "$w/.claude/rules/coding/records-sealed.md" ] && echo yes || echo no)"
  rm -rf "$w"
}
[ "$(jv_case 11)" = "no no" ]   && ok "RULE-15: Java 11 gets neither virtual-threads nor records-sealed" \
                                || bad "RULE-15: Java 11 got a rule for a language feature it does not have — $(jv_case 11)"
[ "$(jv_case 17)" = "no yes" ]  && ok "RULE-15: Java 17 gets records-sealed but not virtual-threads" \
                                || bad "RULE-15: Java 17 gating wrong — $(jv_case 17)"
[ "$(jv_case 21)" = "yes yes" ] && ok "RULE-15: Java 21 gets both (comma-alternative java=17,21 matches)" \
                                || bad "RULE-15: Java 21 gating wrong — $(jv_case 21)"
# an undetected version must not strip rules: Spring Boot 3 floors at 17, so unknown buckets to 17
WB="$(mktemp -d)/repo"; mkdir -p "$WB/src/main/java/com/x"; touch "$WB/src/main/java/com/x/A.java"
printf 'dependencies { implementation("org.springframework.boot:spring-boot-starter-web") }\n' > "$WB/build.gradle.kts"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$WB" >/dev/null 2>&1
[ -f "$WB/.claude/rules/coding/records-sealed.md" ] \
  && ok "RULE-15: an undetected Java version buckets to 17, not legacy (no silent rule loss)" \
  || bad "RULE-15: an undetected Java version silently stripped records-sealed"
rm -rf "$WB"

echo; echo "== RULE-03/04: JPA-only rules must not land in an r2dbc project =="
# transaction-propagation.md and lombok-jpa-safety.md shipped untagged, so they installed everywhere.
# Every ewallet service checked is r2dbc (they carry framework/r2dbc.md, not jpa.md) and party-ms and
# auth-ms each received both JPA rules anyway -- reactive services told how to annotate a Lombok @Entity.
W9="$(mktemp -d)/repo"; mkdir -p "$W9/src/main/java/com/x"; touch "$W9/src/main/java/com/x/A.java"
printf 'dependencies { implementation("org.springframework.boot:spring-boot-starter-data-r2dbc") }\n' > "$W9/build.gradle.kts"
CLAUDE_PLUGIN_ROOT="$ROOT" "$INIT" "$W9" >/dev/null 2>&1
F9="$W9/.claude/rules/framework"
[ -f "$F9/r2dbc.md" ] && ok "RULE-03: r2dbc fixture receives r2dbc.md" || bad "RULE-03: r2dbc fixture did not receive r2dbc.md"
[ -f "$F9/transaction-propagation.md" ] \
  && bad "RULE-03: JPA transaction-propagation.md installed into an r2dbc project" \
  || ok "RULE-03: transaction-propagation.md is gated off an r2dbc project"
